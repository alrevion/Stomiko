-- 067_fix_conflict_arbiter
--
-- В 065 я сделал уникальный индекс ЧАСТИЧНЫМ (where visit_service_id is not
-- null), а в ON CONFLICT предикат не повторил. Postgres такой индекс
-- арбитром не принимает и падает с 42P10.
--
-- Цена ошибки была не в переносе истории, а в работе врача: тот же
-- ON CONFLICT стоит в триггере запечатывания, то есть ЗАКРЫТИЕ ПРИЁМА
-- падало бы у всех. Нашлось на первом же запуске переноса — но найтись
-- должно было на тесте закрытия, которого я не написал.
--
-- Частичный индекс тут вообще не нужен: обычный UNIQUE считает NULL
-- различными, и множество записей-дополнений без visit_service_id ему не
-- мешает. Меньше механики — меньше мест для такой ошибки.
drop index if exists clinical_one_per_service;
create unique index clinical_one_per_service on clinical_entries (visit_service_id);;
